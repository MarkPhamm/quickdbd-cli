"""`qdbd import dbt`: turn a dbt project's manifest.json (+ optional catalog.json) into QuickDBD text.

- Tables: models, seeds and snapshots of the selected packages, plus sources.
- Columns: documented columns, catalog columns (with real types) and columns used by tests.
- Primary keys: `primary_key` constraints, else the first column with both `unique` and
  `not_null` tests. Other `unique` columns get UNIQUE.
- Relationships: `relationships` tests (incl. dbt_utils `relationships_where`) and
  `foreign_key` constraints. A unique child column gives one-to-one (`-`), otherwise many-to-one (`>-`).
- Descriptions become QuickDBD doc comments.
"""

from __future__ import annotations

import fnmatch
import json
import re
from dataclasses import dataclass, field
from pathlib import Path

HEADER = "# Generated by qdbd import dbt"
TABLE_TYPES = ("model", "seed", "snapshot")
REL_TESTS = ("relationships", "relationships_where")
_IDENT = re.compile(r"^[A-Za-z0-9_]+$")
_REF = re.compile(
    r"""^\s*ref\(\s*['"]([^'"]+)['"]\s*(?:,\s*['"]([^'"]+)['"]\s*)?(?:,\s*v(?:ersion)?\s*=\s*\S+\s*)?\)\s*$"""
)
_SOURCE = re.compile(r"""^\s*source\(\s*['"]([^'"]+)['"]\s*,\s*['"]([^'"]+)['"]\s*\)\s*$""")
_TYPE_ALIASES = {
    "character varying": "varchar",
    "timestamp without time zone": "timestamp",
    "timestamp with time zone": "timestamptz",
    "time without time zone": "time",
    "time with time zone": "timetz",
    "double precision": "double",
}


_ENTITY = re.compile(r"^(.+?)(_id|_key|_sk|Id|ID|Key)$")
_LAYERS = ("staging_", "stg_", "int_", "base_", "raw_", "src_", "dim_", "fct_", "fact_", "mart_", "d_", "f_")


def _layer(name: str) -> tuple[str, str]:
    """Split a model name into (layer, entity).

    Handles dbt's naming conventions:
      stg_orders                    -> ("stg_", "orders")
      stg_jaffle_shop__orders       -> ("stg_", "orders")       source-qualified staging models
      conformed__dim_airline        -> ("dim_", "airline")      folder/group__prefix_entity
      bronze__achievements          -> ("bronze__", "achievements")
    """
    low = name.lower()
    head = ""
    if "__" in low:
        head, low = low.rsplit("__", 1)
        head += "__"
    for p in _LAYERS:
        if low.startswith(p) and len(low) > len(p):
            return p, low[len(p) :]
    for p in _LAYERS:
        if head.startswith(p):
            return p, low
    return head, low


def _prefix_rank(child: str, parent: str) -> int:
    """Lower is better: facts point at dimensions; otherwise stay within the same layer (stg_ -> stg_)."""
    if child in ("fct_", "fact_", "f_") and parent in ("dim_", "d_"):
        return 0
    return 1 if parent == child else 2


def _same_entity(table_base: str, entity: str) -> bool:
    forms = {entity, entity + "s", entity + "es"}
    if entity.endswith("y"):
        forms.add(entity[:-1] + "ies")
    return table_base in forms


def _key_column(t: Tbl, name: str) -> Col | None:
    """The parent column an `<entity>_id` points at: same name, else `id`; primary keys first."""

    def norm(n: str) -> str:  # customer_id == customerId == CUSTOMER_ID
        return n.lower().replace("_", "")

    cols = {norm(c.name): c for c in t.cols.values()}
    same, plain = cols.get(norm(name)), cols.get("id")
    for c in (same, plain):
        if c is not None and c.pk:
            return c
    return same or plain


class DbtImportError(Exception):
    pass


@dataclass
class Col:
    name: str
    type: str | None = None
    description: str = ""
    pk: bool = False
    unique: bool = False
    not_null: bool = False
    fk: tuple[str, str, str] | None = None  # (op, parent table uid, parent column)
    order: int = 10_000


@dataclass
class Tbl:
    uid: str
    name: str  # display name in the .txt
    group: str
    description: str = ""
    cols: dict[str, Col] = field(default_factory=dict)

    def col(self, name: str) -> Col:
        key = name.lower()
        for k, c in self.cols.items():
            if k.lower() == key:
                return c
        c = self.cols[name] = Col(name)
        return c


@dataclass
class ImportResult:
    files: dict[str, str]  # file name -> text
    tables: int
    relationships: int
    skipped: list[str]
    inferred: list[str] = field(default_factory=list)
    no_columns: int = 0  # tables with no known columns (undocumented, and no catalog.json)
    catalog: bool = False


def _strip_quotes(s: str) -> str:
    s = s.strip()
    if len(s) >= 2 and s[0] == s[-1] and s[0] in "\"'`[":
        return s[1:-1]
    if s.startswith("[") and s.endswith("]"):
        return s[1:-1]
    return s


def norm_type(t: str | None) -> str | None:
    if not t:
        return None
    t = t.strip()
    low = t.lower()
    for long, short in _TYPE_ALIASES.items():
        if low.startswith(long):
            t = short + t[len(long) :]
            break
    t = re.sub(r"\s*,\s*", ",", t)
    t = re.sub(r"\s*\(\s*", "(", t)
    t = re.sub(r"\s*\)", ")", t)
    t = re.sub(r"\s+", "_", t)
    return t.replace("=", ":").replace("#", "").replace('"', "")


def quote(name: str) -> str:
    name = name.replace('"', "'")
    return name if _IDENT.match(name) else f'"{name}"'


def _comment_lines(text: str) -> list[str]:
    out = []
    for line in (text or "").replace("\r", "").split("\n"):
        line = " ".join(line.split()).replace("#", "＃")
        if line:
            out.append(f"# {line}")
    return out


class _Importer:
    def __init__(
        self,
        manifest: dict,
        catalog: dict | None,
        packages: list[str] | None,
        select: list[str],
        sources: bool,
        infer: bool = False,
    ):
        self.m = manifest
        self.infer = infer
        self.inferred: list[str] = []
        self.catalog = catalog or {}
        self.select = select
        self.sources = sources
        root = (manifest.get("metadata") or {}).get("project_name")
        if packages and "all" in packages:
            self.packages = None
        elif packages:
            self.packages = set(packages)
        else:
            self.packages = {root} if root else None
        self.tables: dict[str, Tbl] = {}
        self.skipped: list[str] = []
        self.by_name: dict[str, list[str]] = {}

    # -- selection ----------------------------------------------------------
    def _wanted(self, node: dict) -> bool:
        if self.packages is not None and node.get("package_name") not in self.packages:
            return False
        if not self.select:
            return True
        cands = [node.get("name", ""), ".".join(node.get("fqn", [])), node.get("original_file_path", "")]
        return any(fnmatch.fnmatch(c, pat) for pat in self.select for c in cands)

    @staticmethod
    def _group(node: dict) -> str:
        rt = node["resource_type"]
        if rt == "source":
            return "sources"
        if rt != "model":
            return rt + "s"
        fqn = node.get("fqn", [])
        return fqn[1] if len(fqn) > 2 else "models"

    def collect(self) -> None:
        nodes = [n for n in self.m.get("nodes", {}).values() if n.get("resource_type") in TABLE_TYPES]
        if self.sources:
            nodes += list(self.m.get("sources", {}).values())
        nodes = [n for n in nodes if self._wanted(n)]
        names: dict[str, int] = {}
        for n in nodes:
            names[self._base_name(n)] = names.get(self._base_name(n), 0) + 1
        for n in sorted(nodes, key=lambda n: n["unique_id"]):
            name = self._base_name(n)
            if names[name] > 1:  # same name in two packages
                name = f"{n.get('package_name')}.{name}"
            t = Tbl(n["unique_id"], name, self._group(n), n.get("description") or "")
            self._columns(t, n)
            self.tables[t.uid] = t
            self.by_name.setdefault(n.get("name", "").lower(), []).append(t.uid)
            if n.get("resource_type") == "source":
                self.by_name.setdefault(f"source:{n['source_name']}.{n['name']}".lower(), []).append(t.uid)

    @staticmethod
    def _base_name(n: dict) -> str:
        if n.get("resource_type") == "source":
            return f"{n['source_name']}.{n['name']}"
        return n.get("name", "")

    def _columns(self, t: Tbl, n: dict) -> None:
        cat = (self.catalog.get("sources" if n["resource_type"] == "source" else "nodes") or {}).get(n["unique_id"])
        if cat:
            for cname, c in cat.get("columns", {}).items():
                col = t.col(c.get("name") or cname)
                col.type = c.get("type")
                col.order = int(c.get("index") or col.order)
        for i, (cname, c) in enumerate(n.get("columns", {}).items()):
            col = t.col(c.get("name") or cname)
            col.description = c.get("description") or ""
            col.type = col.type or c.get("data_type")
            if not cat:
                col.order = i
            for con in c.get("constraints") or []:
                self._constraint(t, col, con)
        for con in n.get("constraints") or []:
            cols = con.get("columns") or []
            if con.get("type") == "primary_key":
                for cn in cols:
                    t.col(cn).pk = True
            elif con.get("type") == "unique" and len(cols) == 1:
                t.col(cols[0]).unique = True
            elif con.get("type") == "foreign_key" and len(cols) == 1:
                self._constraint(t, t.col(cols[0]), con)

    def _constraint(self, t: Tbl, col: Col, con: dict) -> None:
        kind = con.get("type")
        if kind == "primary_key":
            col.pk = True
        elif kind == "unique":
            col.unique = True
        elif kind == "not_null":
            col.not_null = True
        elif kind == "foreign_key":
            target, tcol = con.get("to"), (con.get("to_columns") or [None])[0]
            if not target and con.get("expression"):  # "other_table (id)"
                m = re.match(r"\s*([\w.\"`]+)\s*\(\s*([\w\"`]+)\s*\)", con["expression"])
                if m:
                    target, tcol = m.group(1).split(".")[-1].strip('"`'), m.group(2).strip('"`')
            # Resolved in link(): the target table may not have been collected yet.
            self._constraint_fks.append((t.uid, col.name, target or "", tcol or ""))

    _pending: list[tuple[str, str, str, str]]
    _constraint_fks: list[tuple[str, str, str, str]]

    def _resolve(self, text: str) -> str | None:
        m = _REF.match(text)
        if m:
            name = (m.group(2) or m.group(1)).lower()
        else:
            s = _SOURCE.match(text)
            name = f"source:{s.group(1)}.{s.group(2)}".lower() if s else text.strip().lower()
        uids = self.by_name.get(name, [])
        return uids[0] if len(uids) == 1 else None

    # -- tests --------------------------------------------------------------
    def tests(self) -> None:
        uniq: dict[tuple[str, str], bool] = {}
        notnull: dict[tuple[str, str], bool] = {}
        for n in self.m.get("nodes", {}).values():
            if n.get("resource_type") != "test":
                continue
            meta = n.get("test_metadata") or {}
            kw = meta.get("kwargs") or {}
            name = meta.get("name")
            child = n.get("attached_node") or self._child_from_kwargs(kw)
            colname = _strip_quotes(kw.get("column_name") or n.get("column_name") or "")
            if not child or child not in self.tables or not colname:
                continue
            if name == "unique":
                uniq[(child, colname.lower())] = True
            elif name == "not_null":
                notnull[(child, colname.lower())] = True
            elif name in REL_TESTS:
                deps = [d for d in (n.get("depends_on") or {}).get("nodes", []) if d != child]
                parent = deps[0] if deps else (self._resolve(kw.get("to", "")) or child)
                field_name = _strip_quotes(kw.get("field") or "")
                if parent not in self.tables:
                    self.skipped.append(f"{self.tables[child].name}.{colname}: parent {parent} not in selection")
                    continue
                if field_name:
                    self._pending.append((child, colname, parent, field_name))
        for (uid, cname), _ in uniq.items():
            self.tables[uid].col(cname).unique = True
        for (uid, cname), _ in notnull.items():
            self.tables[uid].col(cname).not_null = True
        for t in self.tables.values():  # implied primary key: unique + not_null
            if any(c.pk for c in t.cols.values()):
                continue
            for c in sorted(t.cols.values(), key=lambda c: c.order):
                if c.unique and c.not_null:
                    c.pk = True
                    break
        for t in self.tables.values():
            for c in t.cols.values():
                if c.pk:
                    c.unique = False

    def _child_from_kwargs(self, kw: dict) -> str | None:
        m = re.search(r"(ref\([^)]*\)|source\([^)]*\))", kw.get("model") or "")
        return self._resolve(m.group(1)) if m else None

    def link(self) -> int:
        for child, ccol, target, tcol in self._constraint_fks:
            parent = self._resolve(target) if target else None
            if parent and tcol:
                self._pending.append((child, ccol, parent, tcol))
            else:
                self.skipped.append(f"{self.tables[child].name}.{ccol}: foreign_key target '{target}' not found")
        count = 0
        seen = set()
        for child, ccol, parent, pcol in self._pending:
            key = (child, ccol.lower(), parent, pcol.lower())
            if key in seen:
                continue
            seen.add(key)
            c = self.tables[child].col(ccol)
            p = self.tables[parent].col(pcol)
            op = "-" if (c.unique or c.pk) else ">-"
            if c.fk is None:
                c.fk = (op, parent, p.name)
            elif p.fk is None:  # one FK per column line: put the second one on the parent side
                p.fk = ({"-": "-", ">-": "-<"}[op], child, c.name)
            else:
                self.skipped.append(
                    f"{self.tables[child].name}.{ccol} -> {self.tables[parent].name}.{pcol}: "
                    "column already has a relationship"
                )
                continue
            count += 1
        return count

    # -- inference from column names (--infer-fks) ---------------------------
    def infer_fks(self) -> int:
        """Link `<entity>_id` columns to the one table named after the entity, when no relationship is declared.

        Candidates are tables whose name, without a dbt layer prefix (stg_, dim_, fct_, ...) and in singular
        or plural, equals the entity, and that have a matching key column. Among several, prefer a dim_ parent
        for a fct_ child, else the same prefix as the child, then the same folder, then a declared primary key;
        a tie is skipped rather than guessed.
        """
        # columns already on the parent side of a declared relationship
        referenced = {(c.fk[1], c.fk[2].lower()) for t in self.tables.values() for c in t.cols.values() if c.fk}
        count = 0
        for t in sorted(self.tables.values(), key=lambda t: t.uid):
            pks = [c for c in t.cols.values() if c.pk]
            for c in sorted(t.cols.values(), key=lambda c: (c.order, c.name.lower())):
                if c.fk is not None or (c.pk and len(pks) == 1) or (t.uid, c.name.lower()) in referenced:
                    continue
                m = _ENTITY.match(c.name)
                if not m:
                    continue
                entity = m.group(1).rstrip("_").lower()
                found = self._infer_target(t, c, entity)
                if found is None:
                    continue
                parent, pcol = found
                c.fk = (">-", parent.uid, pcol.name)
                note = "Relationship inferred from the column name (qdbd import dbt --infer-fks)."
                c.description = (c.description + "\n" if c.description else "") + note
                self.inferred.append(f"{t.name}.{c.name} -> {parent.name}.{pcol.name}")
                count += 1
        return count

    def _infer_target(self, child: Tbl, col: Col, entity: str) -> tuple[Tbl, Col] | None:
        child_prefix = _layer(child.name.split(".")[-1])[0]
        ranked = []
        for t in self.tables.values():
            if t.uid == child.uid:
                continue
            prefix, base = _layer(t.name.split(".")[-1])
            if not _same_entity(base, entity):
                continue
            key = _key_column(t, col.name)
            if key is None:
                continue
            score = (_prefix_rank(child_prefix, prefix), t.group != child.group, not key.pk)
            ranked.append((score, t, key))
        if not ranked:
            return None
        ranked.sort(key=lambda r: r[0])
        best = [r for r in ranked if r[0] == ranked[0][0]]
        if len(best) > 1:
            names = ", ".join(sorted(r[1].name for r in best))
            self.skipped.append(f"{child.name}.{col.name}: ambiguous ({names}), not inferred")
            return None
        return best[0][1], best[0][2]

    # -- output -------------------------------------------------------------
    def render_table(self, t: Tbl) -> list[str]:
        lines = _comment_lines(t.description)
        lines += [quote(t.name), "-"]
        for c in sorted(t.cols.values(), key=lambda c: (c.order, c.name.lower())):
            lines += _comment_lines(c.description)
            parts = [quote(c.name)]
            if c.pk:
                parts.append("PK")
            ty = norm_type(c.type)
            if ty:
                parts.append(ty)
            if c.unique:
                parts.append("UNIQUE")
            if c.fk:
                op, uid, pcol = c.fk
                parts += ["FK", op, f"{quote(self.tables[uid].name)}.{quote(pcol)}"]
            lines.append(" ".join(parts))
        return lines

    def run(self) -> tuple[dict[str, list[Tbl]], int]:
        self._pending = []
        self._constraint_fks = []
        self.collect()
        self.tests()
        rels = self.link()
        if self.infer:
            rels += self.infer_fks()
        groups: dict[str, list[Tbl]] = {}
        for t in sorted(self.tables.values(), key=lambda t: (t.group, t.name.lower())):
            groups.setdefault(t.group, []).append(t)
        return groups, rels


def load_json(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise DbtImportError(f"no such file: {path}") from None
    except json.JSONDecodeError as e:
        raise DbtImportError(f"{path}: not valid JSON ({e})") from None


def import_dbt(
    manifest_path: Path,
    catalog_path: Path | None = None,
    packages: list[str] | None = None,
    select: list[str] | None = None,
    sources: bool = True,
    split: bool = False,
    infer_fks: bool = False,
) -> ImportResult:
    if manifest_path.is_dir():
        manifest_path = manifest_path / "manifest.json"
    manifest = load_json(manifest_path)
    if "nodes" not in manifest:
        raise DbtImportError(f"{manifest_path}: not a dbt manifest (no 'nodes')")
    if catalog_path is None and (manifest_path.parent / "catalog.json").exists():
        catalog_path = manifest_path.parent / "catalog.json"
    catalog = load_json(catalog_path) if catalog_path else None
    imp = _Importer(manifest, catalog, packages, select or [], sources, infer=infer_fks)
    groups, rels = imp.run()
    project = (manifest.get("metadata") or {}).get("project_name") or "dbt"
    head = [
        f"{HEADER} from {manifest_path.name} (project {project}).",
        "# Re-run the import to refresh; manual edits will be overwritten.",
        "",
    ]
    files: dict[str, str] = {}
    if split:
        for g, tables in groups.items():
            body: list[str] = list(head)
            for t in tables:
                body += imp.render_table(t) + [""]
            files[f"{g}.txt"] = "\n".join(body).rstrip("\n") + "\n"
    else:
        body = list(head)
        for tables in groups.values():
            for t in tables:
                body += imp.render_table(t) + [""]
        files["schema.txt"] = "\n".join(body).rstrip("\n") + "\n"
    no_columns = sum(1 for t in imp.tables.values() if not t.cols)
    return ImportResult(files, len(imp.tables), rels, imp.skipped, imp.inferred, no_columns, catalog is not None)


def write_result(result: ImportResult, out: Path) -> list[Path]:
    """Write to a .txt file, or into a directory (one file per group). Stale generated files are removed."""
    written: list[Path] = []
    if out.suffix == ".txt":
        if len(result.files) != 1:
            raise DbtImportError("--split needs a directory for -o")
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(next(iter(result.files.values())), encoding="utf-8")
        return [out]
    out.mkdir(parents=True, exist_ok=True)
    for name, text in result.files.items():
        p = out / name
        p.write_text(text, encoding="utf-8")
        written.append(p)
    keep = {p.name for p in written}
    for old in out.glob("*.txt"):
        if old.name not in keep and old.read_text(encoding="utf-8").startswith(HEADER):
            old.unlink()
    return written


def stale_files(result: ImportResult, out: Path) -> list[str]:
    """What `write_result` would change: files that differ, are missing, or would be removed. Empty = up to date."""
    if out.suffix == ".txt":
        text = next(iter(result.files.values()))
        if not out.exists():
            return [f"{out} (missing)"]
        return [] if out.read_text(encoding="utf-8") == text else [f"{out} (out of date)"]
    problems = []
    for name, text in sorted(result.files.items()):
        p = out / name
        if not p.exists():
            problems.append(f"{p} (missing)")
        elif p.read_text(encoding="utf-8") != text:
            problems.append(f"{p} (out of date)")
    if out.is_dir():
        for old in sorted(out.glob("*.txt")):
            if old.name not in result.files and old.read_text(encoding="utf-8").startswith(HEADER):
                problems.append(f"{old} (no longer generated)")
    return problems
